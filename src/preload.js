const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  settings: () => ipcRenderer.invoke('settings:get'),
  version: () => ipcRenderer.invoke('app:version'),
  rate: () => ipcRenderer.invoke('rate:get'),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  pickDir: () => ipcRenderer.invoke('dir:pick'),
  scan: (root, deep) => ipcRenderer.invoke('scan:start', { root, deep }),
  rescan: (dir, deep) => ipcRenderer.invoke('scan:one', { dir, deep }),
  planActions: (items) => ipcRenderer.invoke('action:plan', { items }),
  applyActions: (tokens, confirm) => ipcRenderer.invoke('action:apply', { tokens, confirm }),
  clutterScan: (dirs) => ipcRenderer.invoke('clutter:scan', { dirs }),
  copyReport: (dir) => ipcRenderer.invoke('report:copy', { dir }),
  trend: () => ipcRenderer.invoke('trend:get'),
  testsScan: (dirs) => ipcRenderer.invoke('tests:scan', { dirs }),
  qualityScan: (dirs) => ipcRenderer.invoke('quality:scan', { dirs }),
  setQualitySettings: (patch) => ipcRenderer.invoke('quality:set', patch),
  audit: () => ipcRenderer.invoke('audit:list'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  background: () => ipcRenderer.invoke('background:get'),
  setBackground: (patch) => ipcRenderer.invoke('background:set', patch),
  agents: (allowActions) => ipcRenderer.invoke('agents:status', { allowActions }),
  planAgent: (id, allowActions, remove) => ipcRenderer.invoke('agents:plan', { id, allowActions, remove }),
  planCleanup: (days) => ipcRenderer.invoke('agents:cleanup', { days }),
  agentRules: (dir) => ipcRenderer.invoke('agents:rules', { dir }),
  revealRule: (dir, hash) => ipcRenderer.invoke('agents:reveal-rule', { dir, hash }),
  planAgentFix: (fix) => ipcRenderer.invoke('agents:fix', { fix }),
  agentUsage: (live) => ipcRenderer.invoke('agents:usage', { live }),
  applyAgent: (token) => ipcRenderer.invoke('agents:apply', { token }),
  copyAgent: (id, allowActions) => ipcRenderer.invoke('agents:copy', { id, allowActions }),
  openUrl: (u) => ipcRenderer.invoke('open:url', u),
  openFolder: (d) => ipcRenderer.invoke('open:folder', d),
  setIgnore: (o) => ipcRenderer.invoke('ignore:set', o),
  drift: () => ipcRenderer.invoke('drift:get'),
  initBaseline: () => ipcRenderer.invoke('baseline:init'),
  openBaseline: () => ipcRenderer.invoke('baseline:open'),
  secrets: {
    scan: (dirs) => ipcRenderer.invoke('secrets:scan', { dirs }),
    tools: () => ipcRenderer.invoke('secrets:tools'),
    link: (tool, target) => ipcRenderer.invoke('secrets:link', { tool, target }),
    test: () => ipcRenderer.invoke('secrets:test'),
    plan: (paths) => ipcRenderer.invoke('secrets:plan', { paths }),
    apply: (token) => ipcRenderer.invoke('secrets:apply', { token }),
    verify: () => ipcRenderer.invoke('secrets:verify'),
    skip: (path, reason, remove) => ipcRenderer.invoke('secrets:skip', { path, reason, remove }),
  },
  onDone: (cb) => ipcRenderer.on('scan:done', (_e, d) => cb(d)),
  onBegin: (cb) => ipcRenderer.on('scan:begin', (_e, d) => cb(d)),
  onRepo: (cb) => ipcRenderer.on('scan:repo', (_e, d) => cb(d)),
});
