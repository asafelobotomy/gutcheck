// Findings from the local git state (git-state.js): an unfinished operation, maintenance health and
// the commit identity. Sources are in docs/sources.md and report-gitstate.js.

const { plural, list } = require('./util');
const { OPS } = require('./git-state');

// git-gc defaults: gc.autoPackLimit 50 packs and gc.auto 6700 loose objects, above which `git gc --auto` repacks.
const PACKS_MAX = 50;
const LOOSE_MAX = 6700;
// Commits with another email under your own name, before it counts as a pattern rather than a one-off.
const IDENTITY_MIN = 2;

const differs = (id) => !!id && !id.autoGenerated && id.other.reduce((n, o) => n + o.count, 0) >= IDENTITY_MIN;

function checkOperation(gs) {
  const op = gs.ops[0];
  if (!op) return [];
  const o = OPS[op.kind];
  const more = gs.ops.slice(1).map((x) => OPS[x.kind].label);
  return [{
    id: 'git-op', category: 'Branches', severity: 'warn', title: `A ${o.label} is unfinished`,
    detail: `Git stopped part way${more.length ? ` (a ${more.join(', ')} is also in progress)` : ''}. Finish it with ${o.cont.split('   #')[0]}, or abort it with git ${o.abort.join(' ')}; abort throws away any conflict resolution done so far.`,
    fix: { type: 'git-op-abort', label: `${op.kind === 'bisect' ? 'End' : 'Abort'} the ${op.kind}…`, op: op.kind },
  }];
}

// One finding per repo, for what git's own auto-maintenance would act on.
function checkMaintenance(s) {
  const gs = s.gitState;
  const m = gs.maintenance;
  const st = (s.hygiene && s.hygiene.storage) || {};
  const sig = [];
  if (st.packs > PACKS_MAX) sig.push(`${st.packs} packs (git gc --auto merges them above ${PACKS_MAX})`);
  if (st.loose > LOOSE_MAX) sig.push(`${st.loose.toLocaleString()} loose objects (git gc --auto packs them above ${LOOSE_MAX.toLocaleString()}${st.prunePackable ? `; ${st.prunePackable.toLocaleString()} are already in a pack` : ''})`);
  if (m.gcLogBlocking) sig.push('.git/gc.log from a failed automatic gc, which stops git gc --auto until it is a day old (gc.logExpiry): read it to see why');
  if (!m.commitGraph && m.commits != null && m.commits >= 10000) sig.push('no commit-graph on a long history, so log and merge-base walks are slower');
  if (!sig.length) return [];
  return [{
    id: 'git-maintenance', category: 'Git hygiene', severity: 'info', title: `Git object store needs housekeeping (${plural(sig.length, 'sign')})`,
    detail: `${sig.join('; ')}.${m.registered ? '' : ' This repo is not in your scheduled maintenance list (maintenance.repo), so nothing tidies it in the background.'}`,
    fix: m.registered ? undefined : { type: 'maintenance-register', label: 'Register for maintenance…' },
  }];
}

// Quiet: info, one finding per repo, and only for an address problem that repeats.
function checkIdentity(s) {
  const id = s.gitState.identity;
  if (!id) return [];
  if (id.autoGenerated) {
    return [{ id: 'git-identity', category: 'Git hygiene', severity: 'info', title: 'No git email is set for this repo',
      detail: `Commits would get an address guessed from the user and host names${id.useConfigOnly ? ', but user.useConfigOnly makes git refuse to commit instead' : ''}. Set user.email, or per folder with an includeIf "gitdir:" block in your global config.` }];
  }
  if (!differs(id)) return [];
  const n = id.other.reduce((t, o) => t + o.count, 0);
  return [{ id: 'git-identity', category: 'Git hygiene', severity: 'info', title: `${plural(n, 'recent commit')} by you used another email than ${id.email}`,
    detail: `Of your last ${plural(id.mine, 'commit')} here: ${list(id.other.map((o) => `${o.email} (${o.count})`), 3)}. GitHub links a commit to an account by its email, so these may not show on your profile. Use an includeIf "gitdir:" (or "hasconfig:remote.*.url:") block per folder or host, and user.useConfigOnly=true so git asks instead of guessing.` }];
}

function checkGitState(s) {
  if (!s.gitState) return [];
  return [...checkOperation(s.gitState), ...checkMaintenance(s), ...checkIdentity(s)];
}

// Workspace level: one summary when several repos commit under another address.
function workspaceIdentity(repos) {
  const bad = repos.filter((r) => differs(r.identity));
  if (bad.length < 2) return [];
  return [{
    id: 'ws-git-identity', severity: 'info', title: `${bad.length} repos have recent commits under a different email`,
    detail: `${list(bad.map((r) => r.name), 8)}. GitHub links commits to your account by email; one global address rarely fits both work and personal repos.`,
    cmds: ['git config --global user.useConfigOnly true   # git asks instead of guessing, in repos with no identity'],
    note: 'Add to ~/.gitconfig: [includeIf "gitdir:~/work/"] path = ~/.gitconfig-work (or [includeIf "hasconfig:remote.*.url:git@github.com:acme/**"]), and put [user] email = you@work.example in that file. Ask which address belongs where first.',
    ref: 'https://git-scm.com/docs/git-config#_conditional_includes',
  }];
}

module.exports = { checkGitState, workspaceIdentity, PACKS_MAX, LOOSE_MAX, IDENTITY_MIN };
