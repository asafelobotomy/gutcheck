const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { scanQuality, normalizeSettings } = require('../src/quality');
const { lex, LANGS } = require('../src/quality/lexer');
const R = require('../src/quality/rules');

const sh = (dir, ...a) => execFileSync('git', a, { cwd: dir, encoding: 'utf8' }).trim();
const put = (dir, rel, content) => { fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); fs.writeFileSync(path.join(dir, rel), content); };
const lines = (n, line = 'x();') => Array.from({ length: n }, () => line).join('\n') + '\n';
function repo() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gutcheck-q-'));
  sh(dir, 'init', '-q', '-b', 'main');
  return dir;
}
// Built at runtime so this repo's own source never contains a secret-looking literal.
const AWS = 'AKIA' + 'ABCDEFGHIJKLMNOP';
const PEM = '-----BEGIN RSA ' + 'PRIVATE KEY-----';
const cleanup = (d) => fs.rmSync(d, { recursive: true, force: true });

test('lexer blanks strings, template literals, regexes and separates comments', () => {
  const r = lex('const a = "x 42"; // TODO 99\nconst t = 3600 * 24; /* 77\n88 */ let z = `a\n 55`; foo(1234); const re = /[0-9]{16}/g;\n', LANGS.js);
  assert.equal(r.code[0], 'const a = ""; ');
  assert.ok(r.comments[0].includes('TODO'));
  assert.equal(r.code.length, 5); // line numbers survive multi-line comments and templates
  assert.ok(!r.code.join('\n').includes('55'));
  assert.ok(!r.code.join('\n').includes('16'));
  assert.ok(r.code.join('\n').includes('1234'));
  assert.deepEqual(lex("fn f<'a>(x: &'a str) { 'x' }\n", LANGS.rs).code[0], "fn f<'a>(x: &'a str) { '' }");
  assert.ok(lex('x = 1  # 42 here\ns = """doc 7\n8"""\n', LANGS.py).code.every((l) => !/42|[78]/.test(l)));
  assert.ok(lex('let a = x / 4 / 8;\n', LANGS.js).code[0].includes('4'), 'division is not a regex');
});

test('magic number rules: allowed values, constant declarations, tables, indices, imports', () => {
  assert.deepEqual(R.magicNumbers('setTimeout(fn, 5000);').map((m) => m.value), [5000]);
  assert.deepEqual(R.magicNumbers('x = a[3] + 0 + 1 + 2 + 10 + 100;'), []);
  assert.deepEqual(R.magicNumbers('const MAX_RETRIES = 5;'), []);
  assert.deepEqual(R.magicNumbers('static final int TIMEOUT = 30;'), []);
  assert.deepEqual(R.magicNumbers('data = [3, 5, 7, 11, 13, 17];'), []);
  assert.deepEqual(R.magicNumbers('import x from "y2";'), []);
  assert.deepEqual(R.magicNumbers('return v1.2.3 + foo2 + 0x1F;').map((m) => m.value), [31]);
  assert.deepEqual(R.constantDef('export const MAX_RETRIES = 5;'), { name: 'MAX_RETRIES', value: 5 });
  assert.deepEqual(R.constantDef('#define BUF_SIZE 4096'), { name: 'BUF_SIZE', value: 4096 });
  assert.equal(R.constantDef('const x = 5;'), null);
});

test('secret rules report kinds, skip placeholders, never expose values', () => {
  assert.deepEqual(R.secretKinds(`k = "${AWS}"`), ['AWS access key']);
  assert.deepEqual(R.secretKinds(PEM), ['Private key']);
  assert.deepEqual(R.secretKinds('password = "Zq8!vK2#pLm9@xR4tW"'), ['Hardcoded credential']);
  assert.deepEqual(R.secretKinds('password = "your_password_here_please"'), []);
  assert.deepEqual(R.secretKinds('token = process.env.TOKEN_VALUE_LONG_ENOUGH'), []);
  assert.deepEqual(R.secretKinds('password = "Zq8!vK2#pLm9@xR4tW"', true), [], 'generic rule is relaxed in test files');
});

test('settings are validated and clamped', () => {
  assert.deepEqual(normalizeSettings(), { maxLines: 400, locMode: 'total', ignore: [] });
  assert.equal(normalizeSettings({ maxLines: 5 }).maxLines, 400);
  assert.equal(normalizeSettings({ maxLines: 1e9 }).maxLines, 400);
  assert.equal(normalizeSettings({ maxLines: '700' }).maxLines, 400);
  assert.equal(normalizeSettings({ maxLines: 250 }).maxLines, 250);
  assert.equal(normalizeSettings({ locMode: 'code' }).locMode, 'code');
  assert.equal(normalizeSettings({ locMode: 'x' }).locMode, 'total');
  assert.deepEqual(normalizeSettings({ ignore: ['a/', 5, '  ', 'b\u0000c'] }).ignore, ['a/', 'bc']);
});

test('LOC limit is user-defined (default 400), counts total or code lines, honours ignores', async () => {
  const dir = repo();
  try {
    put(dir, 'big.js', lines(401));
    put(dir, 'ok.js', lines(400));
    put(dir, 'mostly-comments.js', '// c\n'.repeat(300) + lines(150));
    put(dir, 'legacy/old.js', lines(900));
    put(dir, 'gen.js', '// Code generated by x. DO NOT EDIT.\n' + lines(900));
    put(dir, 'bundle.js', 'a'.repeat(5000) + '\n');
    put(dir, 'node_modules/p/i.js', lines(900));
    put(dir, '.gitignore', 'ignored.js\n');
    put(dir, 'ignored.js', lines(900));
    let q = await scanQuality(dir);
    assert.deepEqual(q.loc.over.map((f) => f.path).sort(), ['big.js', 'legacy/old.js', 'mostly-comments.js']);
    assert.equal(q.skipped.generated, 1);
    assert.equal(q.skipped.minified, 1);
    assert.ok(q.advice.some((a) => a.id === 'q-loc'));

    q = await scanQuality(dir, { maxLines: 800 });
    assert.deepEqual(q.loc.over.map((f) => f.path), ['legacy/old.js']);
    assert.equal(q.advice.find((a) => a.id === 'q-loc').severity, 'info');

    q = await scanQuality(dir, { maxLines: 300, locMode: 'code', ignore: ['legacy/'] });
    assert.deepEqual(q.loc.over.map((f) => f.path).sort(), ['big.js', 'ok.js']); // mostly-comments has only 150 code lines
    assert.equal(q.advice.find((a) => a.id === 'q-loc').severity, 'info');
    q = await scanQuality(dir, { maxLines: 100, ignore: ['*.js'] });
    assert.equal(q.files, 0);
  } finally { cleanup(dir); }
});

test('magic numbers, constants reuse, candidates; tests and strings excluded', async () => {
  const dir = repo();
  try {
    put(dir, 'src/constants.js', 'export const CACHE_TTL_MS = 86400000;\nexport const PAGE = 25;\n');
    put(dir, 'src/a.js', 'const day = 86400000;\nsetTimeout(f, 4242);\nsetTimeout(g, 4242);\nsetTimeout(h, 4242);\nconst s = "9999";\n// 8888\n');
    put(dir, 'src/b.py', 'LIMIT = 500\nx = 750\ny = 750\nz = 750\n');
    put(dir, 'test/a.test.js', 'expect(f()).toBe(31337);\n');
    const q = await scanQuality(dir);
    const files = Object.fromEntries(q.magic.files.map((f) => [f.path, f.count]));
    assert.equal(files['src/a.js'], 4);
    assert.equal(files['src/b.py'], 3);
    assert.equal(files['test/a.test.js'], undefined);
    assert.deepEqual(q.magic.reuse.map((r) => [r.value, r.constant]), [[86400000, 'CACHE_TTL_MS']]);
    assert.deepEqual(q.magic.repeated.map((r) => [r.value, r.count]).sort(), [[4242, 3], [750, 3]]);
    assert.deepEqual(q.magic.constants.files, ['src/constants.js']);
    assert.ok(q.magic.constants.definitions >= 3);
    assert.ok(q.advice.some((a) => a.id === 'q-constants-reuse'));
    assert.ok(q.advice.some((a) => a.id === 'q-constants-candidates'));
    assert.ok(!q.advice.some((a) => a.id === 'q-no-constants'));
  } finally { cleanup(dir); }
});

