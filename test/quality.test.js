test('secrets: kind and location only, never the value; markers; debug; large files; no tests', async () => {
  const dir = repo();
  try {
    put(dir, 'cfg.js', `const k = "${AWS}";\n// TODO: tidy\n// FIXME later\ndebugger;\nconsole.log("x");\n`);
    put(dir, 'run.py', 'import pdb\nx = 1  # HACK around\n');
    for (const n of ['c', 'd', 'e']) put(dir, `${n}.js`, 'x();\n');
    put(dir, 'blob.js', '// ' + 'x'.repeat(6 * 1024 * 1024) + '\n');
    const q = await scanQuality(dir);
    assert.deepEqual(q.secrets.map((s) => [s.path, s.line, s.kind]), [['cfg.js', 1, 'AWS access key']]);
    assert.ok(!JSON.stringify(q).includes(AWS), 'secret values must never appear in results');
    assert.deepEqual([q.markers.TODO, q.markers.FIXME, q.markers.HACK], [1, 1, 1]); // prose that merely mentions TODO is not a marker
    assert.ok(q.debug.some((d) => d.kind === 'debugger'));
    assert.ok(q.debug.some((d) => d.kind === 'breakpoint'));
    assert.equal(q.largeFiles[0].path, 'blob.js');
    fs.writeFileSync(path.join(dir, 'video.mp4'), Buffer.alloc(7 * 1024 * 1024));
    assert.equal((await scanQuality(dir)).largeFiles[0].path, 'video.mp4', 'binaries count, not only source files');
    const ids = q.advice.map((a) => a.id);
    for (const id of ['q-secrets', 'q-markers', 'q-debug', 'q-large-files', 'q-no-tests']) assert.ok(ids.includes(id), id);
    assert.equal(q.advice.find((a) => a.id === 'q-secrets').severity, 'error');
    assert.equal(q.advice.find((a) => a.id === 'q-markers').severity, 'warn'); // a FIXME is present
  } finally { cleanup(dir); }
});

